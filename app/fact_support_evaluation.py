"""Authored, exhaustive claim annotations vs production guards; no semantic judge.

Gold verdicts are reviewed reference data, NEVER generated by the tested rules.
This measures a fixed synthetic corpus, not arbitrary unseen model responses.
"""
import hashlib
import json
from collections import Counter
from datetime import date
from pathlib import Path
from typing import Literal

from pydantic import BaseModel,ConfigDict,Field,model_validator
from .dialogue import CHARACTER,conflicts
from .grounding import grounding_conflicts
from .memory_source import source_time_conflicts
from .weather import weather_reply_conflicts
from .emotion import emotion_reply_conflicts

ROOT=Path(__file__).resolve().parent.parent
DATASET=ROOT/'evaluations/fact_support_dev.json'


class Record(BaseModel):
    model_config=ConfigDict(extra='forbid',strict=True)


class Evidence(Record):
    id: str=Field(min_length=1)
    kind: Literal['canon','memory','user']
    text: str=Field(min_length=1)
    event_date: str | None=None

    @model_validator(mode='after')
    def valid_date(self):
        if self.event_date is not None: date.fromisoformat(self.event_date)
        return self


class Claim(Record):
    id: str=Field(min_length=1)
    start: int=Field(ge=0)
    end: int=Field(gt=0)
    text: str=Field(min_length=1)
    kind: Literal['assertion','epistemic','question','suggestion','conditional','quotation']
    verdict: Literal['supported','contradicted','unsupported','unresolved','not_applicable']
    proposition: str=Field(min_length=3)
    basis_ids: list[str]
    rationale: str=Field(min_length=6)
    form_violation: bool=False
    form_reason: str=''

    @model_validator(mode='after')
    def consistent(self):
        factual=self.kind in ('assertion','epistemic')
        if factual == (self.verdict=='not_applicable'): raise ValueError('claim kind/verdict mismatch')
        if not factual and self.basis_ids: raise ValueError('nonfactual segment cannot earn evidence coverage')
        if self.verdict=='contradicted' or (self.verdict=='supported' and self.kind=='assertion'):
            if not self.basis_ids: raise ValueError('fact basis required')
        if self.form_violation and (self.kind!='assertion' or not self.form_reason.strip()):
            raise ValueError('entity form violation needs asserted span and reason')
        if not self.form_violation and self.form_reason: raise ValueError('orphan form reason')
        if len(self.basis_ids)!=len(set(self.basis_ids)): raise ValueError('duplicate basis')
        return self


class Case(Record):
    id: str=Field(min_length=1)
    family: str=Field(min_length=1)
    category: Literal['paraphrase','scene','place','source_time','mixed','nonassertion']
    origin: Literal['authored','historical_gemini']
    provenance: str=Field(min_length=5)
    query: str=Field(min_length=1)
    reply: str=Field(min_length=1)
    evidence_ids: list[str]
    required_evidence_ids: list[str]
    coverage_reviewed: Literal[True]
    claims: list[Claim]=Field(min_length=1)

    @model_validator(mode='after')
    def coverage(self):
        cursor=0
        if len({c.id for c in self.claims})!=len(self.claims): raise ValueError('duplicate claim id')
        if len(self.evidence_ids)!=len(set(self.evidence_ids)): raise ValueError('duplicate context evidence')
        if len(self.required_evidence_ids)!=len(set(self.required_evidence_ids)): raise ValueError('duplicate obligations')
        if not set(self.required_evidence_ids)<=set(self.evidence_ids): raise ValueError('obligation outside context')
        for c in self.claims:
            if c.start!=cursor or c.end<=c.start or self.reply[c.start:c.end]!=c.text:
                raise ValueError('claims must exactly partition complete reply, without gaps/overlap')
            if not set(c.basis_ids)<=set(self.evidence_ids): raise ValueError('basis outside exposed context')
            cursor=c.end
        if cursor!=len(self.reply): raise ValueError('unannotated reply tail')
        return self


class Dataset(Record):
    version: str=Field(min_length=1)
    source: Literal['synthetic']
    split: Literal['dev']
    annotation_method: Literal['author_reference_not_independent']
    character_sha256: str=Field(pattern=r'^[a-f0-9]{64}$')
    evidence: list[Evidence]=Field(min_length=1)
    cases: list[Case]=Field(min_length=1)

    @model_validator(mode='after')
    def references(self):
        ids={e.id for e in self.evidence}
        if len(ids)!=len(self.evidence) or len({c.id for c in self.cases})!=len(self.cases):
            raise ValueError('duplicate evidence/case id')
        canon={c['id']:c['text'] for c in CHARACTER['canon']}
        by_id={e.id:e for e in self.evidence}
        if {e.id:e.text for e in self.evidence if e.kind=='canon'}!=canon:
            raise ValueError('reference canon differs from production')
        for case in self.cases:
            if not set(case.evidence_ids)<=ids: raise ValueError('unknown exposed evidence')
            if not set(canon)<=set(case.evidence_ids): raise ValueError('production provides complete canon')
            for id in case.evidence_ids:
                e=by_id[id]
                if e.kind=='user' and e.text!=case.query: raise ValueError('user evidence must be actual current message')
        return self


def load_dataset(path=DATASET):
    raw=Path(path).read_bytes()
    data=Dataset.model_validate_json(raw)
    actual=hashlib.sha256((ROOT/'characters/shen_yan.json').read_bytes()).hexdigest()
    if data.character_sha256!=actual: raise ValueError('canon drift: review reference labels before reuse')
    return data,hashlib.sha256(raw).hexdigest()


def guard_predictions(reply,query,evidence):
    memories=[{'id':e.id,'fact':e.text,'event_date':e.event_date}
              for e in evidence if e.kind=='memory']
    history=[{'role':'user','content':query}]
    # Same checks/OR as /v1/chat, no weather/emotion tools in this corpus.
    return {'grounding':grounding_conflicts(reply,memories,query),
            'source_time':source_time_conflicts(reply,history),
            'canon':conflicts(reply,query),
            'weather':weather_reply_conflicts(reply,None),
            'emotion':emotion_reply_conflicts(reply,None)}


def confusion(rows,target):
    excluded=sum(r[target] is None for r in rows)
    rows=[r for r in rows if r[target] is not None]
    tp=sum(r['guarded'] and r[target] for r in rows)
    fp=sum(r['guarded'] and not r[target] for r in rows)
    fn=sum(not r['guarded'] and r[target] for r in rows)
    tn=len(rows)-tp-fp-fn
    return {'eligible':len(rows),'unresolved_excluded':excluded,'tp':tp,'fp':fp,'fn':fn,'tn':tn,
            'precision':tp/(tp+fp) if tp+fp else None,
            'recall':tp/(tp+fn) if tp+fn else None,
            'false_positive_rate':fp/(fp+tn) if fp+tn else None}


def summarize(rows):
    claims=[c for row in rows for c in row['claims']]
    factual=[c for c in claims if c['kind'] in ('assertion','epistemic')]
    counts=dict(Counter(c['verdict'] for c in factual))
    with_facts=[r for r in rows if r['factual_claim_count']]
    obligations=sum(r['obligation_count'] for r in rows)
    return {'responses':len(rows),'factual_claims':len(factual),'claim_verdicts':counts,
            'supported_claim_fraction':counts.get('supported',0)/len(factual) if factual else None,
            'responses_with_facts':len(with_facts),
            'fully_supported_responses':sum(r['semantic_unsafe'] is False for r in with_facts),
            'fully_supported_response_fraction':sum(r['semantic_unsafe'] is False for r in with_facts)/len(with_facts) if with_facts else None,
            'nonfactual_only_responses':len(rows)-len(with_facts),
            'unresolved_responses':sum(any(c['verdict']=='unresolved' for c in r['claims']) for r in rows),
            'strict_entity_form_violations':sum(r['form_violation'] for r in rows),
            'required_evidence_coverage':sum(r['obligation_hits'] for r in rows)/obligations if obligations else None,
            'obligation_hits':sum(r['obligation_hits'] for r in rows),'obligations':obligations,
            'semantic_confusion':confusion(rows,'semantic_unsafe'),
            'policy_confusion':confusion(rows,'policy_unsafe')}


def evaluate(path=DATASET):
    data,digest=load_dataset(path)
    evidence={e.id:e for e in data.evidence}
    rows=[]
    for case in data.cases:
        flags=guard_predictions(case.reply,case.query,[evidence[i] for i in case.evidence_ids])
        factual=[c for c in case.claims if c.kind in ('assertion','epistemic')]
        unsafe=True if any(c.verdict in ('unsupported','contradicted') for c in factual) else None if any(c.verdict=='unresolved' for c in factual) else False
        form=any(c.form_violation for c in case.claims)
        supported={i for c in case.claims if c.kind=='assertion' and c.verdict=='supported' for i in c.basis_ids}
        guarded=any(flags.values())
        row={'id':case.id,'family':case.family,'category':case.category,'origin':case.origin,
             'query':case.query,'reply':case.reply,'provenance':case.provenance,
             'evidence':[evidence[i].model_dump() for i in case.evidence_ids],
             'claims':[c.model_dump() for c in case.claims],
             'factual_claim_count':len(factual),'semantic_unsafe':unsafe,'form_violation':form,
             'policy_unsafe':True if form else unsafe,'guarded':guarded,'guards':flags,
             'obligation_count':len(case.required_evidence_ids),
             'obligation_hits':len(supported & set(case.required_evidence_ids))}
        row['finding']='miss' if row['policy_unsafe'] is True and not guarded else 'overblock' if guarded and row['policy_unsafe'] is False else 'unresolved' if row['policy_unsafe'] is None else None
        rows.append(row)
    guard_files=('app/grounding.py','app/memory_source.py','app/dialogue.py','app/weather.py','app/emotion.py')
    return {'suite':'m5-full-fact-support-v1','dataset_version':data.version,'dataset_sha256':digest,
            'split':'dev','annotation_method':data.annotation_method,'model_calls':0,'database_calls':0,
            'character_version':CHARACTER['version'],
            'guard_sha256':{p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in guard_files},
            'summary':summarize(rows),
            'categories':{name:summarize([r for r in rows if r['category']==name]) for name in sorted({r['category'] for r in rows})},
            'origins':{name:summarize([r for r in rows if r['origin']==name]) for name in sorted({r['origin'] for r in rows})},
            'findings':[r for r in rows if r['finding']], 'results':rows,
            'limits':['Fixed authored synthetic annotations, not semantic inference on arbitrary text.',
                      'Offsets enforce text coverage, not semantic atomicity or annotation correctness.',
                      'Author reference labels are not independent human double review or model judgments.',
                      'Development corpus contains historical failures; not heldout performance or live generation quality.',
                      'Entity form policy is separate from semantic entailment; compare both confusion matrices.',
                      'No facts means no factual support denominator; unresolved labels are not passes and excluded from confusion; obligations track omission.',
                      'Response-level OR guards do not localize individual claims; support proportions describe this constructed corpus, not model performance.',
                      'No tool/weather/emotion evidence here; no rewrite, frontend, retrieval quality, or latency benchmark.']}
